// Regenerates THIRD_PARTY_LICENSES.md: every open-source package shipped in
// the Quire desktop app (JavaScript UI + Rust core) with its licence text.
//   node scripts/licenses.mjs
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

function licenseText(dir) {
  if (!dir || !existsSync(dir)) return null;
  const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  if (!files.length) return null;
  return files.map((f) => readFileSync(join(dir, f), "utf8").trim()).join("\n\n");
}

const entries = [];

// JavaScript packages bundled into the app's UI (production dependencies only),
// read from node_modules so it works offline.
const tree = JSON.parse(
  execSync("pnpm --filter @quire/desktop list --prod --depth Infinity --json", { cwd: root, encoding: "utf8", maxBuffer: 256 << 20 }),
);
const jsSeen = new Set();
const visit = (deps) => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    const key = `${name}@${d.version}`;
    if (jsSeen.has(key) || !d.path) continue;
    jsSeen.add(key);
    let pkg = {};
    try {
      pkg = JSON.parse(readFileSync(join(d.path, "package.json"), "utf8"));
    } catch {}
    const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "see repository";
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
    const url = pkg.homepage ?? (repo ? repo.replace(/^git\+/, "").replace(/\.git$/, "") : "");
    entries.push({ kind: "JavaScript", name, version: d.version, license, url, text: licenseText(d.path) });
    visit(d.dependencies);
  }
};
for (const project of tree) visit(project.dependencies);

// Rust crates compiled into the app (normal dependencies, excluding Quire itself).
const meta = JSON.parse(
  execSync("cargo metadata --format-version 1 --manifest-path apps/desktop/src-tauri/Cargo.toml", { cwd: root, encoding: "utf8", maxBuffer: 256 << 20 }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const seen = new Set();
const walk = (id) => {
  if (seen.has(id)) return;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null)) walk(d.pkg);
  }
};
walk(meta.resolve.root);
for (const id of seen) {
  const p = byId.get(id);
  if (!p || p.name === "quire") continue;
  const dir = p.manifest_path.replace(/\/Cargo\.toml$/, "");
  entries.push({ kind: "Rust", name: p.name, version: p.version, license: p.license ?? "see repository", url: p.repository ?? "", text: licenseText(dir) });
}

// Bundled font.
entries.push({
  kind: "Font",
  name: "Bricolage Grotesque",
  version: "",
  license: "OFL-1.1",
  url: "https://github.com/ateliertriay/bricolage",
  text: readFileSync(join(root, "apps/desktop/src/assets/fonts/OFL-bricolage-grotesque.txt"), "utf8").trim(),
});

entries.sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

let md = `# Third-party licences

Quire is licensed under AGPL-3.0 (see [LICENSE](LICENSE)). The desktop app includes the open-source software below, each under its own licence. Generated by \`node scripts/licenses.mjs\`.

| Package | Version | Licence |
| --- | --- | --- |
${entries.map((e) => `| ${e.url ? `[${e.name}](${e.url})` : e.name} (${e.kind}) | ${e.version} | ${e.license} |`).join("\n")}

## Licence texts
`;
const printed = new Map();
for (const e of entries) {
  md += `\n### ${e.name}${e.version ? ` ${e.version}` : ""}\n\n`;
  if (!e.text) {
    md += `Licensed under ${e.license}. Full text: https://spdx.org/licenses/${encodeURIComponent(e.license.split(/\s/)[0])}.html\n`;
  } else if (printed.has(e.text)) {
    md += `Same licence text as ${printed.get(e.text)} above.\n`;
  } else {
    printed.set(e.text, `${e.name}${e.version ? ` ${e.version}` : ""}`);
    md += "```text\n" + e.text.replace(/```/g, "'''") + "\n```\n";
  }
}
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`${entries.length} packages, ${(md.length / 1024).toFixed(0)} KB`);
